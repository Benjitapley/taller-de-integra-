\set ON_ERROR_STOP on
BEGIN;
-- Serialize SCRUM-101 provisioners in this database.
SELECT pg_catalog.pg_advisory_xact_lock(101, 10);
\ir checks/target.sql
\ir checks/pristine.sql

CREATE ROLE scrum101_owner NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE sql_auth_users LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE sql_listado_applications LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE sql_match_conexion LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE sql_convivencia_mensajeria LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE sql_reportes LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;

REVOKE ALL ON DATABASE roomies_scrum101_disposable FROM PUBLIC;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT CREATE, CONNECT ON DATABASE roomies_scrum101_disposable TO scrum101_owner;
GRANT CONNECT ON DATABASE roomies_scrum101_disposable
    TO sql_auth_users, sql_listado_applications, sql_match_conexion,
       sql_convivencia_mensajeria, sql_reportes;
ALTER DEFAULT PRIVILEGES FOR ROLE scrum101_owner REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE scrum101_owner REVOKE USAGE ON TYPES FROM PUBLIC;

\ir checks/provisioned.sql
COMMIT;
