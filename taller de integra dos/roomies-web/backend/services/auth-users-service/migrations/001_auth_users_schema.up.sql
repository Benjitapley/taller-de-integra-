-- Solo para desarrollo local aislado en roomies_auth_users_dev o para la base
-- de pruebas local aislada roomies_auth_users_test mediante pruebas opt-in.
-- No está autorizada para producción. Aplicar como rol migrador después de
-- crear el rol de runtime sql_auth_users.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
          FROM pg_roles r
         WHERE r.rolname = 'sql_auth_users'
           AND r.rolcanlogin
           AND NOT r.rolsuper
           AND NOT r.rolinherit
           AND NOT r.rolcreatedb
           AND NOT r.rolcreaterole
           AND NOT r.rolreplication
           AND NOT r.rolbypassrls
           AND NOT EXISTS (
               SELECT 1
                 FROM pg_auth_members m
                WHERE m.member = r.oid OR m.roleid = r.oid
           )
    ) THEN
        RAISE EXCEPTION 'sql_auth_users debe ser un login dedicado sin privilegios heredados';
    END IF;
END
$$;

CREATE SCHEMA auth_users;
REVOKE ALL ON SCHEMA auth_users FROM PUBLIC;
CREATE TABLE auth_users.usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supabase_user_id UUID NOT NULL UNIQUE,
    nombre VARCHAR(200) NOT NULL CHECK (length(btrim(nombre)) > 0),
    fecha_nacimiento DATE NOT NULL,
    edad SMALLINT NULL CHECK (edad IS NULL OR edad BETWEEN 0 AND 120),
    ocupacion VARCHAR(100) NULL,
    ciudad VARCHAR(100) NULL,
    breve_descripcion VARCHAR(255) NULL,
    sobre_mi VARCHAR(5000) NULL,
    foto_perfil TEXT NULL
);

REVOKE ALL ON TABLE auth_users.usuario FROM PUBLIC;
